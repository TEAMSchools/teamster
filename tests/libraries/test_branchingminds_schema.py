@pytest.mark.parametrize("model_name", HEADERS)
def test_model_fields_match_slugified_headers(model_name: str):
    model = getattr(schema, model_name)

    assert list(model.model_fields) == HEADERS[model_name]
    assert all(
        f.annotation == str | None and f.default is None
        for f in model.model_fields.values()
    )
