with
    unioned as (
        select
            _dbt_source_relation,
            _dbt_source_project,
            student_number,
            state_student_id,
            academic_year,
            administration_period,
            administration_round,
            administration_round as season,
            test_date,
            assessment_name,
            assessment_type,
            results_type,
            district_state,
            raw_subject,
            subject_area,
            aligned_subject,
            discipline,
            module_code,
            aligned_test_code,
            test_grade,
            grade_level_when_assessed,
            scale_score,
            performance_level,
            performance_level_label,
            is_proficient,
            is_proficient_int,
            is_approaching_int,
            is_below_int,
            aggregated_proficiency,
            performance_band_group_label,
            aligned_performance_band_group,
            lep_status,
            is_504,
            iep_status,
            race_ethnicity,
            aligned_ml_status,
            aligned_aggregate_ethnicity,
            aligned_iep_status,

            'state_nj' as score_source,
            'pearson' as crosswalk_source_system,
        from {{ ref("int_assessments__state_nj_scores") }}

        union all

        select
            _dbt_source_relation,
            _dbt_source_project,
            student_number,
            student_id as state_student_id,
            academic_year,
            administration_window as administration_period,
            administration_window as administration_round,
            season,
            test_date,
            assessment_name,
            assessment_type,
            results_type,
            district_state,
            assessment_subject as raw_subject,
            assessment_subject as subject_area,
            assessment_subject as aligned_subject,
            discipline,
            test_code as module_code,
            test_code as aligned_test_code,

            grade_level as test_grade,
            cast(null as int64) as grade_level_when_assessed,

            scale_score,
            performance_level,
            achievement_level as performance_level_label,
            is_proficient,
            is_proficient_int,
            is_approaching_int,
            is_below_int,
            fast_aggregated_proficiency as aggregated_proficiency,
            fast_performance_band_group_label as performance_band_group_label,
            aligned_performance_band_group,

            cast(null as bool) as lep_status,
            cast(null as bool) as is_504,
            cast(null as string) as iep_status,
            cast(null as string) as race_ethnicity,
            cast(null as string) as aligned_ml_status,
            cast(null as string) as aligned_aggregate_ethnicity,
            cast(null as string) as aligned_iep_status,

            'state_fl' as score_source,
            'fldoe' as crosswalk_source_system,
        from {{ ref("int_fldoe__all_assessments") }}
    )

select
    u.score_source,
    u._dbt_source_relation,
    u._dbt_source_project,
    u.student_number,
    u.state_student_id,
    u.academic_year,
    u.administration_period,
    u.administration_round,
    u.season,
    u.test_date,
    u.assessment_name,
    u.assessment_type,
    u.results_type,
    u.district_state,
    u.raw_subject,
    u.subject_area,
    u.aligned_subject,
    u.discipline,
    u.module_code,
    u.aligned_test_code,
    u.test_grade,
    u.grade_level_when_assessed,
    u.scale_score,
    u.performance_level,
    u.performance_level_label,
    u.is_proficient,
    u.is_proficient_int,
    u.is_approaching_int,
    u.is_below_int,
    u.aggregated_proficiency,
    u.performance_band_group_label,
    u.aligned_performance_band_group,
    u.lep_status,
    u.is_504,
    u.iep_status,
    u.race_ethnicity,
    u.aligned_ml_status,
    u.aligned_aggregate_ethnicity,
    u.aligned_iep_status,
    u.crosswalk_source_system as source_system,

    coalesce(x.illuminate_subject_area, u.raw_subject) as illuminate_subject_area,
from unioned as u
left join
    {{ ref("stg_google_sheets__assessments__vendor_subject_crosswalk") }} as x
    on u.crosswalk_source_system = x.source_system
    and u.raw_subject = x.raw_subject
